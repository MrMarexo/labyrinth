/**
 * A map's pixels of one kind as a single path: each horizontal run of them
 * one rectangle, so a glyph is one or two elements, not one per pixel.
 */
export function runsPath(map: string[], pixel: string): string {
  let d = "";
  map.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== pixel) continue;
      let end = x;
      while (row[end + 1] === pixel) end++;
      d += `M${x} ${y}h${end - x + 1}v1h${x - end - 1}z`;
      x = end;
    }
  });
  return d;
}
